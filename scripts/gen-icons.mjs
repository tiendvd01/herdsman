// Regenerates every app icon from the single source design (spec 003, FR-008).
//   src/assets/herdsman-mark.svg  full-bleed mark, also used in the app UI and as favicon
//   → src-tauri/icons/icon.svg    macOS grid: 824×824 body centred on a 1024 canvas + soft shadow
//   → icns / png (macOS, Linux) from the padded icon; ico / Square*Logo (Windows) from the full-bleed mark
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src/assets/herdsman-mark.svg');
const iconsDir = join(root, 'src-tauri/icons');
const padded = join(iconsDir, 'icon.svg');

const CANVAS = 1024;
const BODY = 824; // Apple macOS app icon grid
const OFFSET = (CANVAS - BODY) / 2;

const svg = readFileSync(source, 'utf8');
const inner = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
if (!inner) throw new Error(`No <svg> content in ${source}`);

writeFileSync(
  padded,
  `<!-- Generated by scripts/gen-icons.mjs from src/assets/herdsman-mark.svg. Do not edit. -->
<svg xmlns="http://www.w3.org/2000/svg" width="${CANVAS}" height="${CANVAS}" viewBox="0 0 ${CANVAS} ${CANVAS}">
  <defs>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="10" stdDeviation="10" flood-color="#000" flood-opacity="0.3"/>
    </filter>
  </defs>
  <g filter="url(#shadow)" transform="translate(${OFFSET} ${OFFSET}) scale(${BODY / CANVAS})">${inner}</g>
</svg>
`,
);

const tauriIcon = (input, ...args) => execFileSync('pnpm', ['tauri', 'icon', input, ...args], { cwd: root, stdio: 'inherit' });

tauriIcon(padded);

// Windows does not use the macOS grid: keep its icons full-bleed.
const tmp = mkdtempSync(join(tmpdir(), 'herdsman-icons-'));
try {
  tauriIcon(source, '-o', tmp);
  for (const f of readdirSync(tmp)) {
    if (f === 'icon.ico' || /^Square\d+x\d+Logo\.png$/.test(f) || f === 'StoreLogo.png') copyFileSync(join(tmp, f), join(iconsDir, f));
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

// No mobile targets.
for (const d of ['android', 'ios']) rmSync(join(iconsDir, d), { recursive: true, force: true });
