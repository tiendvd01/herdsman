// Regenerates every app icon from the single source design (spec 003, FR-008).
//   src/assets/herdsman_lightmode.png  source art (herdsman_darkmode.png is the dark-mode twin used in the UI)
//   → src-tauri/icons/icon.svg    macOS grid: 824×824 body centred on a 1024 canvas + soft shadow
//   → icns / png (macOS, Linux) from the padded icon; ico / Square*Logo (Windows) from the full-bleed mark
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'src-tauri/icons');
const padded = join(iconsDir, 'icon.svg');

const CANVAS = 1024;
const BODY = 824; // Apple macOS app icon grid
const OFFSET = (CANVAS - BODY) / 2;

// Source art: src/assets/herdsman_lightmode.png (bundle icon; the UI swaps to herdsman_darkmode.png in dark mode).
const png = readFileSync(join(root, 'src/assets/herdsman_lightmode.png')).toString('base64');
const art = `<image href="data:image/png;base64,${png}" width="${CANVAS}" height="${CANVAS}" preserveAspectRatio="xMidYMid slice"/>`;
const body = (clip) => `<defs><clipPath id="c"><rect width="${CANVAS}" height="${CANVAS}" rx="${clip}"/></clipPath></defs><g clip-path="url(#c)">${art}</g>`;

writeFileSync(
  padded,
  `<!-- Generated by scripts/gen-icons.mjs from src/assets/herdsman_lightmode.png. Do not edit. -->
<svg xmlns="http://www.w3.org/2000/svg" width="${CANVAS}" height="${CANVAS}" viewBox="0 0 ${CANVAS} ${CANVAS}">
  <defs>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="10" stdDeviation="10" flood-color="#000" flood-opacity="0.3"/>
    </filter>
  </defs>
  <g filter="url(#shadow)" transform="translate(${OFFSET} ${OFFSET}) scale(${BODY / CANVAS})">${body(230)}</g>
</svg>
`,
);
const fullBleed = join(root, 'src-tauri/icons/.full-bleed.svg');
writeFileSync(fullBleed, `<svg xmlns="http://www.w3.org/2000/svg" width="${CANVAS}" height="${CANVAS}" viewBox="0 0 ${CANVAS} ${CANVAS}">${art}</svg>`);

const tauriIcon = (input, ...args) => execFileSync('pnpm', ['tauri', 'icon', input, ...args], { cwd: root, stdio: 'inherit' });

tauriIcon(padded);

// Windows does not use the macOS grid: keep its icons full-bleed.
const tmp = mkdtempSync(join(tmpdir(), 'herdsman-icons-'));
try {
  tauriIcon(fullBleed, '-o', tmp);
  for (const f of readdirSync(tmp)) {
    if (f === 'icon.ico' || /^Square\d+x\d+Logo\.png$/.test(f) || f === 'StoreLogo.png') copyFileSync(join(tmp, f), join(iconsDir, f));
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
  rmSync(fullBleed, { force: true });
}

// No mobile targets.
for (const d of ['android', 'ios']) rmSync(join(iconsDir, d), { recursive: true, force: true });
